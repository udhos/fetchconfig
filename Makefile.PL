#!/usr/bin/perl
#
# Makefile.PL - generate a Makefile for fetchconfig.
#
# Only the test harness is wired up so far:
#
#     perl Makefile.PL      generate the Makefile
#     make test             run the test suite under t/ (via prove)
#
# "make" (the default target) and "make install" are placeholders: they
# print a notice that they are not implemented yet and do nothing else.
# They are intentionally NOT built on ExtUtils::MakeMaker's install
# machinery, because fetchconfig is a standalone script plus a library
# tree deployed by hand (see the README), not a CPAN-style distribution.
#
# This script writes the Makefile itself rather than using
# ExtUtils::MakeMaker, so it has no non-core dependency and behaves
# identically on the AIX and Linux hosts fetchconfig runs on.
#
use strict;
use warnings;

my $perl = $^X;
my $makefile = 'Makefile';

# Locate prove (ships with Test::Harness / perl). Fall back to running the
# .t files directly if prove is somehow absent.
my $test_cmd = "\$(PROVE) -I. t/";

open(my $fh, '>', $makefile) or die "cannot write $makefile: $!\n";
print $fh <<"MAKEFILE";
# Makefile for fetchconfig - generated by Makefile.PL. Do not edit;
# re-run "perl Makefile.PL" to regenerate.

PERL  = $perl
PROVE = prove

# Default target: not implemented yet.
all:
\t\@echo "fetchconfig: 'make' (build) is not implemented yet."
\t\@echo "Available target: 'make test'. See the README for manual installation."

# Run the test suite. Non-zero exit on any failure, so this drops into CI.
test:
\t$test_cmd

# Verbose variant, handy while developing a single test.
test-verbose:
\t\$(PROVE) -v -I. t/

# Installation is done by hand (README); not implemented here.
install:
\t\@echo "fetchconfig: 'make install' is not implemented yet."
\t\@echo "Install manually as described in the README (copy fetchconfig.pl and the"
\t\@echo "fetchconfig/ library tree into place, then set up the device_table)."

clean:
\t-rm -f $makefile

.PHONY: all test test-verbose install clean
MAKEFILE
close($fh);

print "Wrote $makefile.\n";
print "Targets: 'make test' (runs t/); 'make' and 'make install' are placeholders.\n";
